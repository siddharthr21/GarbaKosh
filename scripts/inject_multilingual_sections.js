for (const [lang, phrases] of Object.entries(NEW_PHRASES)) {
  const langKey = `'${lang}': {`;
  const idx = content.indexOf(langKey);
  if (idx === -1) {
    console.error(`Could not find ${langKey} in extendedTranslations.ts`);
    continue;
  }

  // Build the phrases string to inject
  const phraseEntries = Object.entries(phrases)
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');

  // Insert right after `'lang': {\n`
  const insertPos = idx + langKey.length;
  content = content.slice(0, insertPos) + '\n' + phraseEntries + content.slice(insertPos);
}

