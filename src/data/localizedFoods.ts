/**
 * Returns localized food name, serving, benefits, dietType, and glycemicIndex.
 */
export function getLocalizedFoodItem(item: FoodItemPreset, lang: string): {
  name: string;
  serving: string;
  benefits: string;
  dietType: string;
  glycemicIndex: string;
} {
  const code = lang as SupportedLanguageCode;
  const foodOverride = LOCALIZED_FOODS[code]?.[item.id];
  const dietMap = DIET_TYPE_TRANSLATIONS[code] || {};
  const giMap = GLYCEMIC_INDEX_TRANSLATIONS[code] || {};

  return {
    name: foodOverride?.name || item.name,
    serving: foodOverride?.serving || item.serving,
    benefits: foodOverride?.benefits || item.benefits,
    dietType: dietMap[item.dietType] || item.dietType,
    glycemicIndex: giMap[item.glycemicIndex] || item.glycemicIndex
  };
}
