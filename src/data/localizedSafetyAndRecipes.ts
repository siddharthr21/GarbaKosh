/**
 * Returns localized food safety item.
 */
export function getLocalizedSafetyItem(item: FoodSafetyItem, lang: string): FoodSafetyItem {
  const code = lang as SupportedLanguageCode;
  const override = LOCALIZED_SAFETY_ITEMS[code]?.[item.id];
  if (!override) return item;

  return {
    ...item,
    name: override.name || item.name,
    pathogenOrRisk: override.pathogenOrRisk || item.pathogenOrRisk,
    clinicalExplanation: override.clinicalExplanation || item.clinicalExplanation,
    safeAlternative: override.safeAlternative || item.safeAlternative
  };
}

/**
 * Returns localized pregnancy recipe.
 */
export function getLocalizedRecipe(recipe: RecipeItem, lang: string): RecipeItem {
  const code = lang as SupportedLanguageCode;
  const override = LOCALIZED_RECIPES[code]?.[recipe.id];
  if (!override) return recipe;

  return {
    ...recipe,
    title: override.title || recipe.title,
    highlightNutrient: override.highlightNutrient || recipe.highlightNutrient,
    clinicalRationale: override.clinicalRationale || recipe.clinicalRationale,
    ingredients: (override.ingredients as string[]) || recipe.ingredients,
    instructions: (override.instructions as string[]) || recipe.instructions
  };
}
