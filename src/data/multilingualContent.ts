/**
 * Returns a localized WeekData object for any week in 1-40.
 */
export function getLocalizedWeekData(originalWeek: WeekData, lang: string): WeekData {
  const code = lang as SupportedLanguageCode;
  if (!MULTILINGUAL_WEEKS[code] || !MULTILINGUAL_WEEKS[code][originalWeek.week]) {
    return originalWeek;
  }
  const overrides = MULTILINGUAL_WEEKS[code][originalWeek.week];
  return {
    ...originalWeek,
    babySizeFruit: overrides.babySizeFruit || originalWeek.babySizeFruit,
    headline: overrides.headline || originalWeek.headline,
    babyDevelopment: overrides.babyDevelopment || originalWeek.babyDevelopment,
    motherChanges: overrides.motherChanges || originalWeek.motherChanges,
    symptoms: overrides.symptoms || originalWeek.symptoms,
    safeExerciseTip: overrides.safeExerciseTip || originalWeek.safeExerciseTip,
    nutritionTip: overrides.nutritionTip || originalWeek.nutritionTip,
    weeklyAdvice: overrides.weeklyAdvice || originalWeek.weeklyAdvice
  };
}
